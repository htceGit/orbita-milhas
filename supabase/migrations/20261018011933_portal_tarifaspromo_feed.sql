-- The external collector owns fare writes. The portal only reads them.
-- IF NOT EXISTS preserves the table already created by the Railway project.
create table if not exists public.tarifaspromo (
 id bigint generated by default as identity primary key,
 origem varchar not null,
 destino varchar not null,
 origem_nome varchar,
 destino_nome varchar,
 tipo_viagem varchar not null default 'Ida e Volta',
 duracao_dias integer,
 data_ida date not null,
 data_volta date,
 preco numeric not null,
 companhia varchar,
 voos varchar,
 horario_partida varchar,
 horario_chegada varchar,
 duracao_total varchar,
 escalas varchar,
 aeronave varchar,
 link_google_voos text,
 criado_em timestamptz not null default now(),
 atualizado_em timestamptz not null default now(),
 unique(origem,destino,tipo_viagem,duracao_dias,data_ida,data_volta)
);
alter table public.tarifaspromo enable row level security;
drop policy if exists "Permitir leitura pública de tarifaspromo" on public.tarifaspromo;
drop policy if exists "Permitir escrita autenticada" on public.tarifaspromo;
drop policy if exists "Permitir escrita por service_role" on public.tarifaspromo;
revoke all on public.tarifaspromo from public,anon,authenticated;
grant select on public.tarifaspromo to authenticated;
grant all on public.tarifaspromo to service_role;
create policy tarifaspromo_active_read on public.tarifaspromo
 for select to authenticated using ((select private.is_active()));
-- service_role bypasses RLS and keeps the new collector's writes working.
do $$ declare sequence_name text; begin
 sequence_name:=pg_get_serial_sequence('public.tarifaspromo','id');
 if sequence_name is not null then
  execute format('grant usage,select on sequence %s to service_role',sequence_name);
 end if;
end $$;
create index if not exists tarifaspromo_portal_price_idx on public.tarifaspromo(preco,id);

create table public.tarifaspromo_favorites (
 user_id uuid not null references public.profiles(id) on delete cascade,
 tarifa_id bigint not null references public.tarifaspromo(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key(user_id,tarifa_id)
);
create index tarifaspromo_favorites_tarifa_idx on public.tarifaspromo_favorites(tarifa_id);
alter table public.tarifaspromo_favorites enable row level security;
revoke all on public.tarifaspromo_favorites from public,anon,authenticated;
grant select,insert,delete on public.tarifaspromo_favorites to authenticated;
grant all on public.tarifaspromo_favorites to service_role;
create policy tarifaspromo_favorites_owner on public.tarifaspromo_favorites
 for all to authenticated
 using(user_id=(select auth.uid()) and (select private.is_active()))
 with check(user_id=(select auth.uid()) and (select private.is_active()));
-- Carry over favorites when the new feed contains the same route and dates.
insert into public.tarifaspromo_favorites(user_id,tarifa_id,created_at)
 select f.user_id,t.id,f.created_at from public.favorites f
 join public.offers o on o.id=f.offer_id
 join public.tarifaspromo t on t.origem=o.origin and t.destino=o.destination
  and t.data_ida=o.departure_date and t.data_volta=o.return_date
 on conflict do nothing;

-- Keep the collector's timestamp trigger and existing view, with safe access.
create or replace function public.handle_updated_at() returns trigger
language plpgsql set search_path='' as $$ begin new.atualizado_em=now();return new;end $$;
drop trigger if exists trg_tarifaspromo_updated_at on public.tarifaspromo;
create trigger trg_tarifaspromo_updated_at before update on public.tarifaspromo
 for each row execute function public.handle_updated_at();
do $$ begin
 if to_regclass('public.vw_melhores_ofertas') is not null then
  execute 'alter view public.vw_melhores_ofertas set (security_invoker=true)';
  execute 'revoke all on public.vw_melhores_ofertas from public,anon';
  execute 'grant select on public.vw_melhores_ofertas to authenticated,service_role';
 end if;
end $$;
